// ─────────────────────────────────────────────
// description 파싱 렌더러
// 지원 패턴:
//   ■ 제목      → 섹션 헤더 카드
//   1. 제목     → 번호 섹션 카드
//   • 항목      → 불릿 리스트 카드
//   일반 문단   → 텍스트 단락
// ─────────────────────────────────────────────
type Block =
  | { kind: "intro"; text: string }
  | { kind: "section"; title: string; body: string[] }
  | { kind: "numbered"; num: string; title: string; body: string[] }
  | { kind: "bullets"; items: string[] }
  | { kind: "para"; text: string }
  | { kind: "heading"; text: string };

function parseDescription(raw: string): Block[] {
  const lines = raw.split("\n");
  const blocks: Block[] = [];
  let i = 0;

  while (i < lines.length) {
  const line = lines[i].trim();

  // 빈 줄 스킵
  if (!line) { i++; continue; }

  // # 인트로 (캡슐 없이 큰 글씨)
  if (line.startsWith("#")) {
    const text = line.replace(/^#\s*/, "");
    blocks.push({ kind: "intro", text });
    i++;
    continue;
  }

  // ~ 인트로 (# 과 동일하게 처리)
  if (line.startsWith("~")) {
    const text = line.replace(/^~\s*/, "");
    blocks.push({ kind: "intro", text });
    i++;
    continue;
  }
    
    // ■ 섹션 헤더
    if (line.startsWith("■")) {
      const title = line.replace(/^■\s*/, "");
      const body: string[] = [];
      i++;
      while (i < lines.length) {
        const next = lines[i].trim();
        if (!next) { i++; break; }
        // 다음 ■ 섹션이나 다음 numbered만 중단, •와 - 는 본문으로 포함
        if (next.startsWith("■") || /^\d+\.\s/.test(next) || /^\d+$/.test(next)) break;
        body.push(next);
        i++;
      }
      blocks.push({ kind: "section", title, body });
      continue;
    }

    // 1. 번호 섹션 (숫자. 제목)
    const numMatch = line.match(/^(\d+)\.\s+(.+)/);
    if (numMatch) {
      const num = numMatch[1];
      const title = numMatch[2];
      const body: string[] = [];
      i++;
      while (i < lines.length) {
        const next = lines[i].trim();
        if (!next) { i++; if (i < lines.length && /^\d+\./.test(lines[i].trim())) break; continue; }
        if (/^\d+\./.test(next)) break;
        body.push(next);
        i++;
      }
      blocks.push({ kind: "numbered", num, title, body });
      continue;
    }

    // 단독 숫자 줄 (숫자만 있는 줄 = numbered 시작 신호)
    const bareNumMatch = line.match(/^(\d+)$/);
    if (bareNumMatch) {
      const num = bareNumMatch[1];
      i++;
      // 다음 비어있지 않은 줄이 제목
      while (i < lines.length && !lines[i].trim()) i++;
      const title = i < lines.length ? lines[i].trim() : "";
      if (title) i++;
      const body: string[] = [];
      while (i < lines.length) {
        const next = lines[i].trim();
        if (!next) { i++; if (i < lines.length && /^\d+$/.test(lines[i].trim())) break; continue; }
        if (/^\d+$/.test(next) || /^\d+\.\s/.test(next)) break;
        body.push(next);
        i++;
      }
      blocks.push({ kind: "numbered", num, title, body });
      continue;
    }

    // • 불릿 그룹 (연속된 • 줄들을 하나의 카드로)
    if (line.startsWith("•")) {
      const items: string[] = [];
      while (i < lines.length) {
        const next = lines[i].trim();
        if (!next) { i++; break; }
        if (!next.startsWith("•")) break;
        items.push(next.replace(/^•\s*/, ""));
        i++;
      }
      blocks.push({ kind: "bullets", items });
      continue;
    }

    // - 대시 불릿 (연속된 - 줄들을 하나의 카드로)
    if (line.startsWith("- ")) {
      const items: string[] = [];
      while (i < lines.length) {
        const next = lines[i].trim();
        if (!next) { i++; break; }
        if (!next.startsWith("- ")) break;
        items.push(next.replace(/^-\s*/, ""));
        i++;
      }
      blocks.push({ kind: "bullets", items });
      continue;
    }

    // 일반 문단 (연속된 줄을 하나의 단락으로 합침)
    const paraLines: string[] = [];
    while (i < lines.length) {
      const next = lines[i].trim();
      if (!next) { i++; break; }
      if (next.startsWith("~") || next.startsWith("■") || next.startsWith("•") || next.startsWith("- ") || /^\d+\.\s/.test(next) || /^\d+$/.test(next)) break;
      paraLines.push(next);
      i++;
    }
    if (paraLines.length > 0) {
      blocks.push({ kind: "para", text: paraLines.join(" ") });
    }
  }

  return blocks;
}

