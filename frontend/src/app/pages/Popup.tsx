// section → 헤더 카드 + 본문
// numbered → 번호 배지 카드
// bullets → 배경 카드 안 리스트
// para → 연한 배경 카드 단락
// ─────────────────────────────────────────────
function UnifiedDescription({ text }: RichDescriptionProps) {
  const blocks = parseDescription(text);

  // 연속된 para 블록을 하나로 합치기
  type MergedBlock =
    | { kind: "intro"; text: string }
    | { kind: "section"; title: string; body: string[] }
    | { kind: "numbered"; num: string; title: string; body: string[] }
    | { kind: "bullets"; items: string[] }
    | { kind: "paras"; texts: string[] }
    | { kind: "heading"; text: string };


  const merged: MergedBlock[] = [];
  for (const block of blocks) {
    if (block.kind === "para") {
      const last = merged[merged.length - 1];
      if (last && last.kind === "paras") {
        last.texts.push(block.text);
      } else {
        merged.push({ kind: "paras", texts: [block.text] });
      }
    } else {
      merged.push(block as MergedBlock);
    }
  }

  return (
  <div className="space-y-3">
    {merged.map((block, idx) => {

      if (block.kind === "intro") {
        return (
          <div key={idx} className="mb-4 px-1">
           <p className="text-base leading-5 font-medium text-on-surface-variant whitespace-pre-line">
              {block.text}
            </p>
          </div>
        );
      }

      if (block.kind === "heading") {
        return (
          <h3 key={idx} className="text-base md:text-lg font-black text-[#1A237E] dark:text-indigo-300 font-headline tracking-tight mt-2 mb-1">
            {block.text}
          </h3>
        );
      }

      // ■ 섹션 — numbered와 동일 스타일
      if (block.kind === "section") {
          return (
            <div key={idx} className="rounded-xl border border-violet-200/60 dark:border-violet-800/40 bg-white/80 dark:bg-slate-900/30 shadow-sm overflow-hidden">
              <div className="flex items-center gap-3 px-4 py-2.5 border-b border-violet-200/40 bg-gradient-to-r from-[#1A237E]/8 to-[#1A237E]/4 dark:from-[#1A237E]/20 dark:to-transparent">
                <span className="w-1 h-3.5 rounded-full bg-[#7C4DFF] flex-shrink-0" />
                <h4 className="text-xs md:text-sm font-black text-[#1A237E] dark:text-indigo-300 font-headline tracking-tight">
                  {block.title}
                </h4>
              </div>
              {block.body.length > 0 && (
                <div className="px-4 py-3 space-y-1.5">
                  {block.body.map((line, li) => {
                    const isBullet = line.startsWith("•") || line.startsWith("- ");
                    const text = isBullet ? line.replace(/^[•-]\s*/, "") : line;
                    const colonIdx = text.indexOf(":");
                    const hasLabel = isBullet && colonIdx > 0 && colonIdx < 20;
                    const label = hasLabel ? text.slice(0, colonIdx).trim() : null;
                    const body = hasLabel ? text.slice(colonIdx + 1).trim() : text;
                    if (isBullet) {
                      return (
                        <div key={li} className="flex items-start gap-2">
                          <span className="w-1.5 h-1.5 rounded-full bg-[#7C4DFF] flex-shrink-0 mt-1.5" />
                          <p className="text-xs md:text-sm leading-relaxed text-on-surface">
                            {label && <span className="font-semibold text-[#1A237E] dark:text-indigo-300 mr-1">{label}:</span>}
                            {body}
                          </p>
                        </div>
                      );
                    }
                    return <p key={li} className="text-xs md:text-sm leading-relaxed text-on-surface-variant">{line}</p>;
                  })}
                </div>
              )}
            </div>
          );
        }

        // 1. 번호 — 퍼플 그라디언트 헤더 + 흰 본문
        if (block.kind === "numbered") {
          return (
            <div key={idx} className="rounded-xl border border-violet-200/60 dark:border-violet-800/40 bg-white/80 dark:bg-slate-900/30 shadow-sm overflow-hidden">
              <div className="flex items-center gap-3 px-4 py-2.5 border-b border-violet-200/40 bg-gradient-to-r from-[#1A237E]/8 to-[#1A237E]/4 dark:from-[#1A237E]/20 dark:to-transparent">
                <div className="w-5 h-5 rounded-full bg-[#1A237E] flex items-center justify-center flex-shrink-0 shadow-sm">
                  <span className="text-[9px] font-black text-white leading-none">{block.num}</span>
                </div>
                <h4 className="text-xs md:text-sm font-bold text-[#1A237E] dark:text-indigo-300">
                  {block.title}
                </h4>
              </div>
              {block.body.length > 0 && (
                <div className="px-4 py-3 space-y-1.5">
                  {block.body.map((line, li) => {
                    if (line.startsWith("•")) {
                      return (
                        <div key={li} className="flex items-start gap-2">
                          <span className="w-1 h-1 rounded-full bg-[#7C4DFF] flex-shrink-0 mt-1.5" />
                          <p className="text-xs md:text-sm leading-relaxed text-on-surface-variant">{line.replace(/^•\s*/, "")}</p>
                        </div>
                      );
                    }
                    return (
                      <p key={li} className="text-xs md:text-sm leading-relaxed text-on-surface-variant">{line}</p>
                    );
                  })}
                </div>
              )}
            </div>
          );
        }

        // • 불릿 — numbered와 동일 스타일
        if (block.kind === "bullets") {
          return (
            <div key={idx} className="rounded-xl border border-violet-200/60 dark:border-violet-800/40 bg-white/80 dark:bg-slate-900/30 shadow-sm px-4 py-3 space-y-2">
              {block.items.map((item, ii) => {
                const colonIdx = item.indexOf(":");
                const hasLabel = colonIdx > 0 && colonIdx < 20;
                const label = hasLabel ? item.slice(0, colonIdx).trim() : null;
                const body  = hasLabel ? item.slice(colonIdx + 1).trim() : item;
                return (
                  <div key={ii} className="flex items-start gap-2.5">
                    <span className="w-1.5 h-1.5 rounded-full bg-[#7C4DFF] flex-shrink-0 mt-1.5" />
                    <p className="text-xs md:text-sm leading-relaxed text-on-surface">
                      {label && (
                        <span className="font-semibold text-[#1A237E] dark:text-indigo-300 mr-1">{label}:</span>
                      )}
                      {body}
                    </p>
                  </div>
                );
              })}
            </div>
          );
        }

        // 합쳐진 para — section과 동일 스타일 (연보라 헤더 + 흰 본문)
        if (block.kind === "paras") {
          return (
            <div key={idx} className="rounded-xl border border-violet-200/60 dark:border-violet-800/40 bg-white/80 dark:bg-slate-900/30 shadow-sm overflow-hidden">
              <div className="h-1 bg-gradient-to-r from-[#1A237E]/40 to-[#1A237E]/10" />
              <div className="px-4 py-3.5 space-y-2.5">
                {block.texts.map((t, ti) => (
                  <p key={ti} className="text-xs md:text-sm leading-relaxed text-on-surface">
                    {t}
                  </p>
                ))}
              </div>
            </div>
          );
        }

        return null;
      })}
    </div>
  );
}

