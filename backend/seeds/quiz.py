def seed(db: Session):
    existing = db.query(QuizQuestion).count()
    if existing >= len(QUIZ_QUESTIONS):
        print(f"✅ 퀴즈 시드 완료 (0개 추가, {existing}개 이미 존재)")
        return

    added = 0
    for q in QUIZ_QUESTIONS:
        exists = db.query(QuizQuestion).filter(QuizQuestion.question == q["question"]).first()
        if not exists:
            db.add(QuizQuestion(**q))
            added += 1

    db.commit()
    print(f"✅ 퀴즈 시드 완료 ({added}개 추가, {existing}개 이미 존재)")
