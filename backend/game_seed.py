def _split_hint(description: str) -> tuple[str, str | None]:
    """👉 기준으로 본문과 힌트를 분리한다. 힌트가 없으면 None 반환."""
    if "👉" in description:
        body, hint = description.rsplit("👉", 1)
        return body.rstrip(), hint.strip()
    return description, None


def seed():
    db = next(get_db())
    try:
        total_added = 0
        for s in SCENARIOS:
            info = s["info"]
            existing = db.query(GameScenario).filter_by(scenario_key=info["scenario_key"]).first()
            if existing:
                print(f"⚠️  {info['name']} '{info['theme']}' 이미 존재 (id={existing.id}) — 건너뜀")
                continue

            scenario = GameScenario(**info)
            db.add(scenario)
            db.flush()

            for asset, daily_prices in s["prices"].items():
                for day_idx, price in enumerate(daily_prices, start=1):
                    db.add(GameDayPrice(scenario_id=scenario.id, day_index=day_idx, asset=asset, price=price))

            for day_idx, cpi, interest_rate, fx_usdkrw, vix in s["macros"]:
                db.add(GameDayMacro(
                    scenario_id=scenario.id, day_index=day_idx,
                    cpi=cpi, interest_rate=interest_rate, fx_usdkrw=fx_usdkrw, vix=vix,
                ))

            for day_idx, slot, title, description, news_type in s["news"]:
                desc, hint = _split_hint(description)
                db.add(GameDayNews(
                    scenario_id=scenario.id, day_index=day_idx, slot=slot,
                    title=title, description=desc, hint=hint, news_type=news_type,
                ))

            trap_count = sum(1 for n in s["news"] if n[4] == "trap")
            price_count = sum(len(v) for v in s["prices"].values())
            print(f"✅ {info['name']} '{info['theme']}' (id={scenario.id}) "
                  f"— 가격 {price_count}개 / 거시 {len(s['macros'])}개 / 뉴스 {len(s['news'])}개 (함정 {trap_count}개)")
            total_added += 1

        db.commit()
        if total_added:
            print(f"\n🎉 총 {total_added}개 시나리오 시드 완료")
        else:
            print("\n✔️  모든 시나리오가 이미 존재합니다")

    except Exception as e:
        db.rollback()
        print(f"🚨 시드 실패: {e}")
        raise
    finally:
        db.close()


